            "علم" to listOf("🇸🇦", "🇪🇬", "🇦🇪", "🇵🇸", "🇰🇼")
        )
        for ((k, list) in keywordMap) {
            if (k.contains(q) || q.contains(k)) {
                return list
            }
        }
        for (cat in categories) {
            if (cat.title.lowercase().contains(q)) {
                return cat.emojis
            }
        }
        return categories.first().emojis.take(24)
    }
